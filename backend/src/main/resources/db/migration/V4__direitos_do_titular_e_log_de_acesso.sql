-- RF10 (direitos do titular, LGPD Art. 18) e RF11 (registro de acesso,
-- LGPD Art. 46).

-- Momento em que o titular pediu a eliminacao dos seus dados. Nulo =
-- cadastro normal. Preenchido = em janela de arrependimento: os dados
-- ficam bloqueados (fora das listagens e consultas) por 30 dias e,
-- passado esse prazo, sao apagados definitivamente.
ALTER TABLE profissional ADD COLUMN data_exclusao_solicitada timestamp;

-- Quem consultou ou alterou dado pessoal, quando, e de qual registro.
-- Sem isso nao ha como responder "quem viu esses dados?", detectar uso
-- indevido, nem instruir a comunicacao de incidente do Art. 48.
CREATE TABLE log_acesso (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora     timestamp NOT NULL,
    -- Login do usuario quando o RF09 existir. Ate la, 'nao-autenticado':
    -- o sistema ainda nao tem como saber quem e.
    autor         varchar(100) NOT NULL,
    origem        varchar(45),
    acao          varchar(20) NOT NULL,
    entidade      varchar(50) NOT NULL,
    registro_id   bigint,
    detalhe       varchar(255)
);

-- Consulta tipica: "tudo que aconteceu com o registro X".
CREATE INDEX idx_log_acesso_registro ON log_acesso (entidade, registro_id);
-- Consulta tipica: "o que aconteceu no periodo Y".
CREATE INDEX idx_log_acesso_data ON log_acesso (data_hora);
