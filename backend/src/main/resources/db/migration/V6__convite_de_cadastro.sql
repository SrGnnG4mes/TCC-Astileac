-- RF12: contas de acesso criadas pelo proprio associado, mediante convite.
--
-- A diretoria emite o convite depois de confirmar o pagamento da
-- associacao; o convite chega por e-mail e serve uma vez so. E o
-- convite que prova que aquela pessoa foi reconhecida como associada --
-- sem ele, qualquer um que soubesse um CPF abriria conta em nome de
-- outra pessoa e alcancaria os dados pessoais dela.

CREATE TABLE convite (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- E-mail para o qual o convite foi emitido. Vira o contato
    -- principal do profissional quando o convite e consumido, para a
    -- pessoa nao redigitar o que a associacao ja sabe.
    email            varchar(150) NOT NULL,

    -- SHA-256 do token, nunca o token em si: ele e credencial
    -- portadora, como senha. Se o banco vazar, os convites guardados
    -- nao podem ser utilizaveis.
    --
    -- SHA-256 e nao BCrypt de proposito. O BCrypt e lento para
    -- proteger segredo de baixa entropia escolhido por humano; o token
    -- aqui tem 256 bits de aleatoriedade e nao se quebra por forca
    -- bruta. Alem disso o BCrypt usa sal por registro, o que obrigaria
    -- a varrer a tabela inteira comparando hash a hash para achar um
    -- convite -- com SHA-256 a busca e direta, pelo indice.
    token_hash       char(64) NOT NULL UNIQUE,

    data_emissao     timestamp NOT NULL,
    data_expiracao   timestamp NOT NULL,

    -- Nulo enquanto nao usado. E o que torna o convite de uso unico.
    data_consumo     timestamp,

    -- Preenchido no consumo: o cadastro que nasceu deste convite.
    profissional_id  bigint UNIQUE REFERENCES profissional (id),

    -- Login de quem emitiu, para o convite tambem ser rastreavel.
    emitido_por      varchar(100) NOT NULL
);

-- A busca do convite e sempre pelo hash do token apresentado.
CREATE INDEX idx_convite_token_hash ON convite (token_hash);

-- Listagem da diretoria: os pendentes primeiro.
CREATE INDEX idx_convite_data_consumo ON convite (data_consumo);

-- O PostgreSQL nao cria indice de chave estrangeira sozinho, e o
-- expurgo precisa achar o convite pelo profissional para apaga-lo.
CREATE INDEX idx_convite_profissional ON convite (profissional_id);
