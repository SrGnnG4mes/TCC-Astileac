-- Schema inicial do ASTILEAC: as 9 tabelas do DER (docs/ASTILEAC-BD.mmd).

CREATE TABLE profissional (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              varchar(150) NOT NULL,
    cpf               varchar(11) NOT NULL UNIQUE,
    data_nascimento   date NOT NULL,
    data_associacao   date NOT NULL,
    ativo             boolean NOT NULL DEFAULT true
);

CREATE TABLE endereco (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id   bigint NOT NULL UNIQUE REFERENCES profissional (id),
    cep               varchar(8) NOT NULL,
    logradouro        varchar(150) NOT NULL,
    numero            varchar(20) NOT NULL,
    complemento       varchar(100),
    bairro            varchar(100) NOT NULL,
    cidade            varchar(100) NOT NULL,
    uf                char(2) NOT NULL
);

CREATE TABLE contato (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id   bigint NOT NULL REFERENCES profissional (id),
    tipo              varchar(20) NOT NULL CHECK (tipo IN ('EMAIL', 'TELEFONE')),
    valor             varchar(150) NOT NULL,
    principal         boolean NOT NULL DEFAULT false
);

CREATE TABLE area_atuacao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome              varchar(50) NOT NULL UNIQUE,
    descricao         varchar(255)
);

-- Ponto central do modelo: relacao N:N entre profissional e area_atuacao.
-- Nunca substituir por colunas booleanas (atua_educacional, etc.).
CREATE TABLE profissional_area (
    profissional_id   bigint NOT NULL REFERENCES profissional (id),
    area_atuacao_id   bigint NOT NULL REFERENCES area_atuacao (id),
    data_inicio       date NOT NULL,
    PRIMARY KEY (profissional_id, area_atuacao_id)
);

CREATE TABLE formacao (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id   bigint NOT NULL REFERENCES profissional (id),
    nivel             varchar(50) NOT NULL,
    curso             varchar(150) NOT NULL,
    instituicao       varchar(150) NOT NULL,
    ano_conclusao     integer NOT NULL
);

CREATE TABLE certificado (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id        bigint NOT NULL REFERENCES profissional (id),
    formacao_id            bigint REFERENCES formacao (id),
    titulo                 varchar(150) NOT NULL,
    instituicao_emissora   varchar(150) NOT NULL,
    carga_horaria          integer NOT NULL,
    data_emissao           date NOT NULL,
    -- Guarda apenas o caminho do arquivo; o binario nunca vai para o banco.
    arquivo_path           varchar(255) NOT NULL
);

CREATE TABLE vinculo_empregaticio (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id   bigint NOT NULL REFERENCES profissional (id),
    instituicao       varchar(150) NOT NULL,
    cargo             varchar(100) NOT NULL,
    tipo_vinculo      varchar(50) NOT NULL,
    data_inicio       date NOT NULL,
    -- data_fim nula = vinculo em andamento. O historico e mantido, nao so o vinculo atual.
    data_fim          date,
    atual             boolean NOT NULL DEFAULT true
);

CREATE TABLE usuario (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profissional_id   bigint UNIQUE REFERENCES profissional (id),
    login             varchar(100) NOT NULL UNIQUE,
    -- Sempre hash (BCrypt via Spring Security), nunca senha em texto.
    senha_hash        varchar(255) NOT NULL,
    perfil            varchar(30) NOT NULL
);
